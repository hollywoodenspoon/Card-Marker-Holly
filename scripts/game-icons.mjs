// Fantasy icons for the app's buttons, from game-icons.net (CC BY 3.0):
//   npm run icons:gen   (writes src/ui/gameIcons.gen.ts with only the icons used)
// The map is: our icon name (as imported in the app) → game-icons name.
import { readFileSync, writeFileSync } from 'node:fs'

export const MAP = {
  // Left rail
  LayoutTemplate: 'scroll-unfurled',
  SquareStack: 'card-draw',
  Library: 'card-random',
  Type: 'quill-ink',
  Printer: 'stamper',
  LayoutGrid: 'portrait',
  Swords: 'crossed-swords',
  ImageDown: 'save-arrow',
  Highlighter: 'magic-swirl',
  PenTool: 'fountain-pen',
  Sheet: 'stone-tablet',
  // Top bar, menus and views
  Menu: 'hamburger-menu',
  Settings2: 'cog',
  Undo2: 'anticlockwise-rotation',
  Redo2: 'clockwise-rotation',
  Home: 'castle',
  Download: 'open-treasure-chest',
  TextSearch: 'magnifying-glass',
  Ruler: 'pencil-ruler',
  Layers: 'stack',
  Wand2: 'wizard-staff',
  Paintbrush: 'paint-brush',
  // Playtest
  Dices: 'rolling-dices',
  Coins: 'coinflip',
  Trophy: 'trophy-cup',
  Flag: 'flying-flag',
  Shuffle: 'cycle',
  ScrollText: 'scroll-quill',
}

const icons = JSON.parse(
  readFileSync(new URL('../node_modules/@iconify-json/game-icons/icons.json', import.meta.url)),
).icons
const missing = Object.values(MAP).filter((n) => !icons[n])
if (missing.length) throw new Error(`Unknown game-icons: ${missing.join(', ')}`)
const lines = Object.entries(MAP).map(
  ([ours, theirs]) =>
    `  ${ours}: ${JSON.stringify(icons[theirs].body.replace(/ fill="currentColor"/g, ''))},`,
)
writeFileSync(
  new URL('../src/ui/gameIcons.gen.ts', import.meta.url),
  `// Generated by scripts/game-icons.mjs from game-icons.net (CC BY 3.0). Do not edit.\n` +
    `// Authors: Lorc, Delapouite and contributors — https://game-icons.net\n` +
    `export const GAME_ICONS = {\n${lines.join('\n')}\n} as const\n`,
)
console.log(`${lines.length} icons`)
